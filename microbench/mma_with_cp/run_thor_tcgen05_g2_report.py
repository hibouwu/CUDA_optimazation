"""Generate, inspect, and run the Thor TCGen05 cta_group::2 microbenchmarks.

The generated kernels time a bundle of BF16 M256N128K16 group2 MMA
instructions, one multicast completion commit, and the completion-wait
boundary (including necessary CTA convergence/control). All setup and TMEM
teardown are deliberately outside the clock64 window.
"""


def log(message: str) -> None:
    print(message, flush=True)


def run_command(
    command: list[str | Path], *, capture: bool = True, echo_output: bool = True
) -> str:
    argv = [str(item) for item in command]
    log("+ " + " ".join(argv))
    completed = subprocess.run(
        argv,
        cwd=ROOT,
        text=True,
        stdout=subprocess.PIPE if capture else None,
        stderr=subprocess.STDOUT if capture else None,
        check=False,
    )
    output = completed.stdout or ""
    if echo_output and output:
        print(output, end="")
    if completed.returncode != 0:
        raise RuntimeError(
            f"command failed with exit code {completed.returncode}: {' '.join(argv)}\n"
            f"{output}"
        )
    return output


def case_id(k_blocks: int) -> str:
    return f"g2_ss_mainloop_k{k_blocks}"


def source_path(k_blocks: int) -> Path:
    return SRC_DIR / (
        f"tcgen05_{case_id(k_blocks)}_m256n128_bf16_benchmark.cu"
    )


def binary_path(k_blocks: int) -> Path:
    return BUILD_DIR / (
        f"tcgen05_{case_id(k_blocks)}_m256n128_bf16_benchmark"
    )


def ensure_dirs() -> None:
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    BUILD_DIR.mkdir(parents=True, exist_ok=True)
    PLOTS_DIR.mkdir(parents=True, exist_ok=True)


def render_source(k_blocks: int) -> str:
    # The legacy group1 sweep reserves at least 32 KiB for each operand and then
    # grows both arrays with the M128N128 BF16 panel size (4096 B per K16).
    smem_bytes = max(32 * 1024, 4096 * k_blocks)
    replacements = {
        "__CASE_ID__": case_id(k_blocks),
        "__K_BLOCKS__": str(k_blocks),
        "__SMEM_A_BYTES__": str(smem_bytes),
        "__SMEM_B_BYTES__": str(smem_bytes),
    }
    source = CU_TEMPLATE
    for placeholder, value in replacements.items():
        source = source.replace(placeholder, value)
    leftovers = sorted(set(TEMPLATE_FIELD_RE.findall(source)))
    if leftovers:
        raise RuntimeError(f"unexpanded source placeholders: {leftovers}")
    return source


def validate_source(path: Path, k_blocks: int) -> None:
    text = path.read_text()
    required = (
        "tcgen05.mma.cta_group::2.kind::f16",
        "tcgen05.alloc.cta_group::2",
        "shared::cluster.multicast::cluster",
        "fence.proxy.async.shared::cta",
        "tcgen05.relinquish_alloc_permit.cta_group::2",
        "tcgen05.dealloc.cta_group::2",
        "cudaLaunchAttributeClusterDimension",
        "attribute.val.clusterDim.x = 2",
        "d |= 16u << 24",
        f"kMainloopKBlocks = {k_blocks}",
    )
    missing = [needle for needle in required if needle not in text]
    if missing:
        raise RuntimeError(f"{path.name} is missing required tokens: {missing}")
    if TEMPLATE_FIELD_RE.search(text):
        raise RuntimeError(f"{path.name} still contains a template placeholder")


def generate_sources() -> list[Path]:
    expected = {source_path(k).name for k in K_BLOCKS}
    for stale in SRC_DIR.glob(
        "tcgen05_g2_ss_mainloop_k*_m256n128_bf16_benchmark.cu"
    ):
        if stale.name not in expected:
            stale.unlink()

    paths = []
    for k_blocks in K_BLOCKS:
        path = source_path(k_blocks)
        path.write_text(render_source(k_blocks))
        validate_source(path, k_blocks)
        paths.append(path)

    actual = {
        path.name
        for path in SRC_DIR.glob(
            "tcgen05_g2_ss_mainloop_k*_m256n128_bf16_benchmark.cu"
        )
    }
    if actual != expected:
        raise RuntimeError(
            "group2 source set mismatch: "
            f"expected {sorted(expected)}, found {sorted(actual)}"
        )
    return paths


def find_tool(name: str) -> str:
    path = shutil.which(name)
    if not path:
        raise RuntimeError(f"required tool not found in PATH: {name}")
    return path


def compile_source(path: Path, k_blocks: int, ccbin: str | None) -> Path:
    nvcc = find_tool("nvcc")
    binary = binary_path(k_blocks)
    command: list[str | Path] = [
        nvcc,
        "-O3",
        "-std=c++17",
        "--expt-relaxed-constexpr",
        # glibc 2.42 exposes C23 rsqrt/rsqrtf under _GNU_SOURCE, which
        # conflicts with CUDA 13.0's device declarations before PTX parsing.
        "-U_GNU_SOURCE",
        "-gencode",
        "arch=compute_110a,code=sm_110a",
    ]
    if ccbin:
        command.extend(["-ccbin", ccbin])
    command.extend([path, "-o", binary])
    run_command(command)
    return binary


def inspect_sass(binary: Path, bundle_mma_count: int) -> list[str]:
    cuobjdump = find_tool("cuobjdump")
    output = run_command(
        [cuobjdump, "--dump-sass", binary], echo_output=False
    )
    mma_lines = [line.strip() for line in output.splitlines() if "UTCHMMA" in line]
    if not mma_lines:
        raise RuntimeError(f"{binary.name}: SASS contains no UTCHMMA")
    if not any("2CTA" in line for line in mma_lines):
        sample = "\n".join(mma_lines[:8])
        raise RuntimeError(
            f"{binary.name}: UTCHMMA found but no 2CTA encoding:\n{sample}"
        )
    # ptxas may unroll the outer iteration loop, so the static instruction
    # count is generally a multiple of q rather than exactly q.
    if len(mma_lines) < bundle_mma_count or len(mma_lines) % bundle_mma_count:
        raise RuntimeError(
            f"{binary.name}: {len(mma_lines)} static UTCHMMA.2CTA instructions "
            f"are not a whole number of K{bundle_mma_count} bundles"
        )
    return mma_lines


def compile_and_inspect(
    sources: list[Path], ccbin: str | None
) -> tuple[dict[int, Path], dict[int, list[str]]]:
    binaries: dict[int, Path] = {}
    sass: dict[int, list[str]] = {}
    for k_blocks, source in zip(K_BLOCKS, sources, strict=True):
        binary = compile_source(source, k_blocks, ccbin)
        lines = inspect_sass(binary, k_blocks)
        binaries[k_blocks] = binary
        sass[k_blocks] = lines
        log(f"SASS K{k_blocks}: {lines[0]}")
    return binaries, sass


def read_frequency(cli_frequency: float | None) -> tuple[float, str]:
    if cli_frequency is not None:
        if cli_frequency <= 0:
            raise RuntimeError("--freq-hz must be positive")
        return cli_frequency, "--freq-hz"
    try:
        value = float(FREQ_SYSFS_PATH.read_text().strip())
        if value > 0:
            return value, str(FREQ_SYSFS_PATH)
    except (OSError, ValueError):
        pass
    return float(DEFAULT_FREQ_HZ), "fallback Thor GPC frequency"


def parse_key_values(output: str) -> dict[str, str]:
    result: dict[str, str] = {}
    for line in output.splitlines():
        if "=" not in line:
            continue
        key, value = line.split("=", 1)
        result[key.strip()] = value.strip()
    return result


